// data/BillCategories.kt
// 轻量"本地支出分类器"：把商家/说明归到少数几类，供三类用途共用同一份口径：
//   · 预算进度统计（按分类算已花）
//   · 实时消费后 AI/悬浮窗提示该分类剩余预算
//   · 后续报表分类占比
// 纯本地关键词规则（端侧），保证离线可用、口径一致。

package com.example.finance.data

object BillCategories {

    val PRESETS = listOf("餐饮", "购物", "日用", "交通", "娱乐", "医疗", "其他")

    fun categorize(merchantRaw: String?, source: String? = null): String {
        val m = merchantRaw?.trim() ?: return "其他"
        val src = source ?: ""
        fun has(vararg keys: String): Boolean = keys.any { m.contains(it) }
        // 平台/来源先验
        val isMeituan = src.contains("美团") || has("外卖订单", "美团")
        return when {
            // 交通
            has("地铁", "公交", "铁路", "高铁", "火车", "机票", "打车", "滴滴", "高德", "曹操出行",
                "出租车", "加油", "停车", "ETC", "共享单车") -> "交通"
            // 医疗
            has("医院", "诊所", "药房", "药", "体检", "挂号", "牙", "眼科") -> "医疗"
            // 娱乐
            has("电影", "影院", "KTV", "游戏", "Steam", "门票", "网吧", "密室", "剧本杀", "游乐园", "视频会员", "音乐") -> "娱乐"
            // 餐饮（美团通道或明显餐饮词）
            isMeituan ||
                    has("外卖", "食堂", "餐", "饭", "面", "粉", "饺", "汉堡", "炸鸡", "鸡排", "烧烤", "烤串",
                        "火锅", "麻辣烫", "寿司", "披萨", "奶茶", "咖啡", "果汁", "甜品", "蛋糕", "面包",
                        "小吃", "宵夜", "早餐", "汤", "粥", "饼", "炒", "便当", "餐厅", "吃货", "美食", "超市便当") -> "餐饮"
            // 日用（超市/便利店/生鲜/家庭消耗）
            has("超市", "便利店", "生鲜", "菜", "粮油", "洗护", "日用品", "五金", "家政", "水电", "燃气") -> "日用"
            // 购物（电商/穿着/数码/家居等商品消费）
            src.contains("淘宝") || src.contains("闪购") ||
                    has("淘宝", "天猫", "京东", "拼多多", "旗舰店", "数码", "手机", "电器", "电脑",
                        "鞋", "衣", "裤", "裙", "包", "饰品", "美妆", "家居", "收纳", "办公用品") -> "购物"
            else -> "其他"
        }
    }
}
